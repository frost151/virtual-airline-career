export type Gender = 'm' | 'f'

/** Полное имя: «Клаус Вебер», «Ольга Николаевна Воронцова». */
export function generateName(country: string, rng: () => number): { name: string; gender: Gender } {
  const c = CULTURES[COUNTRY_CULTURE[country] ?? 'en']
  const gender: Gender = rng() < 0.62 ? 'm' : 'f'
  const first = pick(rng, gender === 'm' ? c.male : c.female)
  let last = pick(rng, c.last)
  if (gender === 'f' && c.femaleLast) last = c.femaleLast(last)
  // Восточноазиатский порядок: фамилия впереди.
  const culture = COUNTRY_CULTURE[country]
  if (culture === 'zh' || culture === 'ko') return { name: `${last} ${first}`, gender }
  if (c.patronymics) {
    const p = pick(rng, c.patronymics)
    return { name: `${first} ${gender === 'm' ? p.m : p.f} ${last}`, gender }
  }
  return { name: `${first} ${last}`, gender }
}
